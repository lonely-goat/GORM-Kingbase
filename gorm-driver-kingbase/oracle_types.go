package kingbase

import (
	"fmt"
	"strings"

	"gorm.io/gorm/schema"
)

func (d *Dialector) oracleDataTypeOf(field *schema.Field) string {
	switch field.DataType {
	case schema.Bool:
		// gokb 的 Oracle OID 表原生支持 BOOL；使用 boolean 可直接向 Go bool 扫描，
		// 避免 NUMBER(1) 在 database/sql 中被作为数值返回后产生 bool 转换歧义。
		return "boolean"
	case schema.Int, schema.Uint:
		return oracleIntegerType(field)
	case schema.Float:
		if field.Precision > 0 {
			return fmt.Sprintf("NUMBER(%d,%d)", field.Precision, field.Scale)
		}
		return "DOUBLE PRECISION"
	case schema.String:
		size := field.Size
		if size == 0 {
			size = int(d.DefaultStringSize)
		}
		if size > 0 && size <= 4000 {
			return fmt.Sprintf("VARCHAR2(%d)", size)
		}
		return "CLOB"
	case schema.Time:
		if field.Precision > 0 || field.TagSettings["PRECISION"] == "0" {
			return fmt.Sprintf("TIMESTAMP(%d) WITH TIME ZONE", field.Precision)
		}
		return "TIMESTAMP WITH TIME ZONE"
	case schema.Bytes:
		return "BLOB"
	default:
		return oracleCustomType(field)
	}
}

func oracleIntegerType(field *schema.Field) string {
	var dataType string
	switch {
	case field.Size <= 8:
		dataType = "tinyint"
	case field.Size <= 16:
		dataType = "smallint"
	case field.Size <= 32:
		dataType = "integer"
	default:
		dataType = "bigint"
	}

	// Oracle 示例方言生成的 NUMBER(20) GENERATED BY DEFAULT AS IDENTITY 被测试实例拒绝；
	// KingbaseES 明确要求 identity 基础类型是整数族，因此这里生成 bigint 等整数类型。
	if field.AutoIncrement {
		dataType += " GENERATED BY DEFAULT AS IDENTITY"
	}
	return dataType
}

func oracleCustomType(field *schema.Field) string {
	dataType := string(field.DataType)
	if dataType == "" {
		dataType = string(field.GORMDataType)
	}
	if field.AutoIncrement && !strings.Contains(strings.ToLower(dataType), "identity") {
		dataType += " GENERATED BY DEFAULT AS IDENTITY"
	}
	return dataType
}
